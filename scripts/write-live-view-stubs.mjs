#!/usr/bin/env node
/**
 * Write thin .js re-export stubs for live-view.
 *
 * Dev (tsx): admin/server imports → admin/shared/live-view/*.js|ts
 *   path to shared/dist: ../../../shared/dist/live-view
 *
 * Prod (node dist/server): imports → admin/dist/shared/live-view/*.js
 *   path to shared/dist: ../../../../shared/dist/live-view
 *   (one extra ../ because of the dist/ prefix)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));

const MODULES = [
  'index',
  'auto',
  'binary',
  'protocol',
  'quality',
  'states',
  'transport-profiles',
  'unchanged',
];

const TARGETS = [];

if (!args.has('--dist-only')) {
  TARGETS.push(
    {
      dir: path.join(root, 'admin', 'shared', 'live-view'),
      importPrefix: '../../../shared/dist/live-view',
    },
    {
      dir: path.join(root, 'desktop', 'src', 'live-view-shared'),
      importPrefix: '../../../shared/dist/live-view',
    }
  );
}

if (args.has('--dist') || args.has('--dist-only')) {
  TARGETS.push({
    dir: path.join(root, 'admin', 'dist', 'shared', 'live-view'),
    importPrefix: '../../../../shared/dist/live-view',
  });
}

const distIndex = path.join(root, 'shared', 'dist', 'live-view', 'index.js');
if (!fs.existsSync(distIndex)) {
  console.error(`Missing ${distIndex} — run shared build first`);
  process.exit(1);
}

if (TARGETS.length === 0) {
  console.error('Usage: write-live-view-stubs.mjs [--dist] [--dist-only]');
  process.exit(1);
}

for (const { dir, importPrefix } of TARGETS) {
  fs.mkdirSync(dir, { recursive: true });
  for (const name of MODULES) {
    const contents =
      `// Generated by scripts/write-live-view-stubs.mjs — do not edit.\n` +
      `export * from '${importPrefix}/${name}.js';\n`;
    fs.writeFileSync(path.join(dir, `${name}.js`), contents, 'utf8');
  }
  console.log(`wrote ${MODULES.length} stubs → ${path.relative(root, dir)}`);
}
